"""Train your own multi-class model for the firmware (e.g. person / door / stairs / car).

Dataset layout (one folder per class; put the background class first alphabetically,
e.g. "0_nothing"):
    dataset/
      0_nothing/  *.jpg|*.png|*.pgm   street/room views with none of the classes
      person/
      door/
      stairs/
      ...
Collect local photos with the device itself: send 's' over the USB serial port to save
the current camera frame to the SD card (/photos/aiNNNNN.pgm), then sort them into folders.

Run (CPU is fine for a few thousand images; Google Colab with a GPU is faster):
    pip install "tensorflow==2.16.*" pillow
    python ml/train_classifier.py dataset --epochs 25 --write-firmware

Output:
    models/vision_classifier.tflite   int8 model
    src/ai/model_data.cpp             (with --write-firmware) C array for the firmware
    src/ai/labels.h                   (with --write-firmware) class names in output order

The model matches the firmware's input convention: 96x96 grayscale, normalised to [-1, 1],
int8 quantised. It uses only ops registered in src/ai/detector.cpp.
"""
import argparse
import pathlib
import subprocess
import sys

import numpy as np
import tensorflow as tf

IMG = 96
ROOT = pathlib.Path(__file__).resolve().parents[1]


def load_datasets(path, batch, val_split):
    common = dict(color_mode="grayscale", image_size=(IMG, IMG), batch_size=batch,
                  validation_split=val_split, seed=42)
    train = tf.keras.utils.image_dataset_from_directory(path, subset="training", **common)
    val = tf.keras.utils.image_dataset_from_directory(path, subset="validation", **common)
    return train, val, train.class_names


def normalise(x, y):
    return x / 127.5 - 1.0, y        # same as detector.cpp: pixel/127.5 - 1


def build_model(num_classes, alpha):
    inp = tf.keras.Input((IMG, IMG, 1))
    # 1x1 conv copies the grey channel into 3 channels so ImageNet weights can be reused.
    rgb = tf.keras.layers.Conv2D(3, 1, use_bias=False, trainable=False,
                                 kernel_initializer=tf.keras.initializers.Ones(), name="gray_to_rgb")(inp)
    base = tf.keras.applications.MobileNet(input_shape=(IMG, IMG, 3), alpha=alpha,
                                           include_top=False, weights="imagenet")
    base.trainable = False
    x = base(rgb, training=False)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    x = tf.keras.layers.Dropout(0.2)(x)
    out = tf.keras.layers.Dense(num_classes, activation="softmax")(x)
    return tf.keras.Model(inp, out), base


def augment():
    return tf.keras.Sequential([
        tf.keras.layers.RandomFlip("horizontal"),
        tf.keras.layers.RandomRotation(0.05),
        tf.keras.layers.RandomZoom(0.15),
        tf.keras.layers.RandomContrast(0.3),
        tf.keras.layers.RandomBrightness(0.25, value_range=(-1, 1)),
    ])


def convert_int8(model, train_ds, out_path):
    def rep():
        for x, _ in train_ds.unbatch().take(300):
            yield [tf.expand_dims(x, 0)]
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = rep
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    out_path.write_bytes(conv.convert())
    print(f"saved {out_path} ({out_path.stat().st_size / 1024:.0f} KB)")


def evaluate_tflite(path, val_ds):
    it = tf.lite.Interpreter(model_path=str(path))
    it.allocate_tensors()
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    s, z = i["quantization"]
    correct = total = 0
    for x, y in val_ds.unbatch():
        q = np.clip(np.floor(x.numpy() / s + 0.5) + z, -128, 127).astype(np.int8)
        it.set_tensor(i["index"], q[None])
        it.invoke()
        correct += int(np.argmax(it.get_tensor(o["index"])[0]) == int(y))
        total += 1
    print(f"int8 model accuracy on validation set: {correct / total:.3f} ({total} images)")


def write_labels(names):
    pretty = [n.split("_", 1)[1] if n[:1].isdigit() and "_" in n else n for n in names]
    lines = "\n".join(f'    "{n}",  // {k}' for k, n in enumerate(pretty))
    (ROOT / "src/ai/labels.h").write_text(
        "#pragma once\n// Generated by ml/train_classifier.py -- class names in model output order.\n"
        "#define AI_BACKGROUND_INDEX 0   // class that means \"nothing to announce\"\n\n"
        f"static const char *const kLabels[] = {{\n{lines}\n}};\n"
        "static const int kNumLabels = sizeof(kLabels) / sizeof(kLabels[0]);\n", encoding="utf-8")
    print("wrote src/ai/labels.h:", pretty)
    print("Record a voice prompt for each new class name (tools/make_prompts.py --extra ...).")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset")
    ap.add_argument("--epochs", type=int, default=25)
    ap.add_argument("--fine-tune-epochs", type=int, default=10)
    ap.add_argument("--batch", type=int, default=32)
    ap.add_argument("--alpha", type=float, default=0.25, help="MobileNet width (0.25 fits the H743 comfortably)")
    ap.add_argument("--val-split", type=float, default=0.2)
    ap.add_argument("--out", default=str(ROOT / "models/vision_classifier.tflite"))
    ap.add_argument("--write-firmware", action="store_true")
    a = ap.parse_args()

    train, val, names = load_datasets(a.dataset, a.batch, a.val_split)
    print("classes:", names, "(index 0 must be the background class)")
    aug = augment()
    train_n = train.map(normalise).map(lambda x, y: (aug(x, training=True), y)).prefetch(2)
    val_n = val.map(normalise).prefetch(2)

    model, base = build_model(len(names), a.alpha)
    model.compile(tf.keras.optimizers.Adam(1e-3), "sparse_categorical_crossentropy", ["accuracy"])
    model.fit(train_n, validation_data=val_n, epochs=a.epochs)

    # Fine-tune the top of the backbone.
    base.trainable = True
    for layer in base.layers[:-20]:
        layer.trainable = False
    model.compile(tf.keras.optimizers.Adam(1e-5), "sparse_categorical_crossentropy", ["accuracy"])
    model.fit(train_n, validation_data=val_n, epochs=a.fine_tune_epochs)

    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    convert_int8(model, train.map(normalise), out)
    evaluate_tflite(out, val_n)

    if a.write_firmware:
        subprocess.run([sys.executable, str(ROOT / "tools/tflite_to_c.py"), str(out),
                        str(ROOT / "src/ai/model_data.cpp")], check=True)
        write_labels(names)
        print("Now rebuild and flash: pio run -t upload")


if __name__ == "__main__":
    main()
